# Internal: Plumber API generator
# ============================================================

#' @keywords internal
.qsr_deploy_api <- function(path, title, include, data, models) {

  api_code <- paste0(
    '# Generated by QUASAR — qsr_deploy(type = "api")\n',
    '# Run with: plumber::pr_run(plumber::pr("plumber.R"))\n\n',
    'library(plumber)\n\n',
    '# Load QUASAR context\n',
    'ctx <- readRDS("quasar_context.rds")\n',
    'data <- ctx$data\n',
    'models <- ctx$models\n\n',
    '#* @apiTitle ', title, '\n',
    '#* @apiDescription REST API generated by QUASAR\n\n'
  )

  if ("data" %in% include && !is.null(data)) {
    api_code <- paste0(api_code,
      '#* Get dataset info\n',
      '#* @get /data/info\n',
      'function() {\n',
      '  list(rows = nrow(data), cols = ncol(data),\n',
      '       columns = names(data),\n',
      '       types = vapply(data, class, character(1)))\n',
      '}\n\n',
      '#* Get data (with optional limit)\n',
      '#* @param limit Number of rows to return\n',
      '#* @get /data\n',
      'function(limit = 100) {\n',
      '  limit <- min(as.integer(limit), nrow(data))\n',
      '  head(data, limit)\n',
      '}\n\n',
      '#* Get summary statistics\n',
      '#* @get /data/summary\n',
      'function() {\n',
      '  num_cols <- names(data)[vapply(data, is.numeric, logical(1))]\n',
      '  lapply(num_cols, function(col) {\n',
      '    x <- data[[col]]\n',
      '    list(column = col, mean = mean(x, na.rm = TRUE),\n',
      '         sd = sd(x, na.rm = TRUE), min = min(x, na.rm = TRUE),\n',
      '         max = max(x, na.rm = TRUE), na_count = sum(is.na(x)))\n',
      '  })\n',
      '}\n\n'
    )
  }

  if ("models" %in% include && length(models) > 0) {
    api_code <- paste0(api_code,
      '#* List available models\n',
      '#* @get /models\n',
      'function() {\n',
      '  lapply(names(models), function(nm) {\n',
      '    m <- models[[nm]]\n',
      '    list(name = nm, type = class(m)[1])\n',
      '  })\n',
      '}\n\n'
    )

    if ("predictions" %in% include) {
      api_code <- paste0(api_code,
        '#* Get predictions from a model\n',
        '#* @param model_name Name of the model\n',
        '#* @post /predict\n',
        'function(req, model_name = "last") {\n',
        '  m <- models[[model_name]]\n',
        '  if (is.null(m)) return(list(error = "Model not found"))\n',
        '  newdata <- tryCatch(jsonlite::fromJSON(req$postBody),\n',
        '                      error = function(e) data)\n',
        '  if (inherits(m, "lm")) {\n',
        '    preds <- predict(m, newdata = as.data.frame(newdata))\n',
        '    list(predictions = as.list(preds))\n',
        '  } else {\n',
        '    list(error = "Prediction not supported for this model type")\n',
        '  }\n',
        '}\n\n'
      )
    }
  }

  api_code <- paste0(api_code,
    '#* Health check\n',
    '#* @get /health\n',
    'function() {\n',
    '  list(status = "ok", framework = "QUASAR",\n',
    '       timestamp = Sys.time())\n',
    '}\n'
  )

  writeLines(api_code, file.path(path, "plumber.R"))
  cli::cli_alert_info("Created {.file plumber.R}")
}
